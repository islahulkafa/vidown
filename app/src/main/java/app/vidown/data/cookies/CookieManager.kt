package app.vidown.data.cookies

import android.content.Context
import android.net.Uri
import java.io.BufferedReader
import java.io.File
import java.io.InputStreamReader

data class CookieSummary(
    val cookieCount: Int,
    val domains: List<String>,
    val lastModified: Long,
    val filePath: String
)

class CookieManager private constructor(private val appContext: Context) {

    private val cookiesDir = File(appContext.filesDir, "cookies").apply { mkdirs() }
    val cookieFile = File(cookiesDir, "cookies.txt")

    fun getCookieSummary(): CookieSummary? {
        if (!cookieFile.exists() || cookieFile.length() == 0L) {
            return null
        }
        val lines = cookieFile.readLines()
        val parsed = parseCookieLines(lines)
        if (parsed.isEmpty()) return null

        val domains = parsed.map { it.domain }.distinct().sorted()
        return CookieSummary(
            cookieCount = parsed.size,
            domains = domains,
            lastModified = cookieFile.lastModified(),
            filePath = cookieFile.absolutePath
        )
    }

    fun hasCookies(): Boolean {
        return cookieFile.exists() && cookieFile.length() > 0L
    }

    fun importFromFile(uri: Uri): Result<CookieSummary> {
        return try {
            val content = appContext.contentResolver.openInputStream(uri)?.use { stream ->
                BufferedReader(InputStreamReader(stream)).readText()
            } ?: return Result.failure(Exception("Could not read selected file"))

            importFromText(content)
        } catch (e: Exception) {
            Result.failure(e)
        }
    }

    fun importFromText(rawText: String): Result<CookieSummary> {
        val lines = rawText.lines()
        val validCookies = parseCookieLines(lines)

        if (validCookies.isEmpty()) {
            return Result.failure(Exception("No valid Netscape cookies found in content. Expected 7 tab-separated columns per cookie."))
        }

        return try {
            cookieFile.bufferedWriter().use { writer ->
                writer.write("# Netscape HTTP Cookie File\n")
                writer.write("# Generated by Vidown\n\n")
                for (line in lines) {
                    val trimmed = line.trim()
                    if (trimmed.isNotBlank()) {
                        writer.write(trimmed)
                        writer.write("\n")
                    }
                }
            }

            val summary = getCookieSummary()
                ?: return Result.failure(Exception("Failed to read back saved cookies"))

            Result.success(summary)
        } catch (e: Exception) {
            Result.failure(e)
        }
    }

    fun clearCookies(): Boolean {
        return if (cookieFile.exists()) {
            cookieFile.delete()
        } else {
            true
        }
    }

    private data class ParsedCookie(val domain: String, val name: String)

    private fun parseCookieLines(lines: List<String>): List<ParsedCookie> {
        val result = mutableListOf<ParsedCookie>()
        for (line in lines) {
            val trimmed = line.trim()
            if (trimmed.isEmpty() || trimmed.startsWith("#")) continue

            val parts = trimmed.split("\t")
            if (parts.size >= 7) {
                val domain = parts[0].trim()
                val name = parts[5].trim()
                if (domain.isNotEmpty() && name.isNotEmpty()) {
                    result.add(ParsedCookie(domain = domain, name = name))
                }
            }
        }
        return result
    }

    companion object {
        @Volatile
        private var instance: CookieManager? = null

        fun getInstance(context: Context): CookieManager {
            return instance ?: synchronized(this) {
                instance ?: CookieManager(context.applicationContext).also { instance = it }
            }
        }
    }
}
